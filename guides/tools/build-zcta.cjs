// Builds data/zcta.js from the US Census 2023 ZCTA Gazetteer (public domain):
// https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_zcta_national.zip
// Usage: node tools/build-zcta.cjs /path/2023_Gaz_zcta_national.txt
const fs = require('fs');
const src = process.argv[2]; const out = {};
for (const line of fs.readFileSync(src, 'utf8').split('\n').slice(1)) {
  const c = line.trim().split('\t'); if (c.length < 7) continue;
  out[c[0]] = [+(+c[5]).toFixed(3), +(+c[6]).toFixed(3)];
}
fs.writeFileSync(__dirname + '/../data/zcta.js', '// Generated by tools/build-zcta.cjs from US Census 2023 ZCTA Gazetteer (INTPTLAT/INTPTLONG). zip -> [lat, lon]\nexport default ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'ZCTAs');
